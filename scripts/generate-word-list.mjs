#!/usr/bin/env node
// Writes demos/desktop/text-spelling-words.ts from a SCOWL word list: lower case, without possessives,
// sorted and front-coded (each entry is how much of the word before it stays, as one character from
// "0", and then the rest).
//
//   node scripts/generate-word-list.mjs [/usr/share/dict/american-english]

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const source = process.argv[2] ?? "/usr/share/dict/american-english";
const notice = process.argv[3] ?? "/usr/share/doc/wamerican/copyright";
const words = [
  ...new Set(
    readFileSync(source, "utf8")
      .split("\n")
      .filter((word) => word.length > 0 && !word.endsWith("'s"))
      .map((word) => word.toLowerCase()),
  ),
].sort();

let last = "";
const entries = words.map((word) => {
  let kept = 0;
  while (kept < last.length && kept < word.length && last[kept] === word[kept]) kept += 1;
  const entry = String.fromCharCode(48 + kept) + word.slice(kept);
  last = word;
  return entry;
});

const NOTICE_HEADING =
  "The word list in text-spelling-words.ts comes from SCOWL, as packaged by Debian's wamerican.\nThis is that package's copyright file, unchanged:\n\n";

const target = path.join(import.meta.dirname, "..", "demos/desktop/text-spelling-words.ts");
writeFileSync(
  target.replace(/\.ts$/, ".NOTICE.txt"),
  NOTICE_HEADING + readFileSync(notice, "utf8"),
);
writeFileSync(
  target,
  `/*
 * Generated by scripts/generate-word-list.mjs from SCOWL (http://wordlist.aspell.net/); do not edit.
 * Copyright 2000-2011 by Kevin Atkinson. The copyrights of the lists SCOWL draws on, and their terms
 * of use, are in text-spelling-words.NOTICE.txt beside this file.
 *
 * Permission to use, copy, modify, distribute and sell these word lists, the associated scripts, the
 * output created from the scripts, and its documentation for any purpose is hereby granted without
 * fee, provided that the above copyright notice appears in all copies and that both that copyright
 * notice and this permission notice appear in supporting documentation. Kevin Atkinson makes no
 * representations about the suitability of this array for any purpose. It is provided "as is"
 * without express or implied warranty.
 */
export const WORD_LIST = ${JSON.stringify(entries.join(" "))};
`,
);
console.log(`${words.length} words, ${entries.join(" ").length} characters`);
